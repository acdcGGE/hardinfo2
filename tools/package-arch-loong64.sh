#!/usr/bin/env bash
# Build an Arch Linux loong64 package (.pkg.tar.zst) for hardinfo2.
#
# Arch's loong64 port has no makepkg/pacman available on this build host, so
# this script produces a standard Arch package layout directly with
# cmake --install + bsdtar --zstd. The result is installable with
# `pacman -U <file>` on an Arch Linux loong64 system.
#
# Prerequisite: an already-configured build tree whose LIBPREFIX is
# /usr/lib/hardinfo2 (i.e. built with -DCMAKE_INSTALL_LIBDIR=lib), e.g.:
#
#   cmake -S . -B build-arch -DCMAKE_BUILD_TYPE=Release \
#         -DCMAKE_INSTALL_LIBDIR=lib -DHARDINFO2_VK_WAYLAND=0
#   cmake --build build-arch -j
#   tools/package-arch-loong64.sh build-arch
set -euo pipefail

BUILD_DIR="${1:-build-arch}"
SRC_DIR="$(cd "$(dirname "$0")/.." && pwd)"
cd "$SRC_DIR"

VERSION="$(grep -m1 'set(HARDINFO2_VERSION' CMakeLists.txt | sed -E 's/.*"([^"]+)".*/\1/')"
PKGVER="${VERSION}-1"
PKGNAME="hardinfo2"
ARCH="loong64"
PKGREL_DATE="$(date +%s)"
PACKAGER="${PACKAGER:-acdcGGE <acdcGGE@users.noreply.github.com>}"

command -v bsdtar >/dev/null || { echo "bsdtar not found" >&2; exit 1; }

STAGE="$(mktemp -d)"
trap 'rm -rf "$STAGE"' EXIT

log() { printf '[arch-loong64] %s\n' "$*" >&2; }

log "installing into staging root"
DESTDIR="$STAGE" cmake --install "$BUILD_DIR" >/dev/null

# Normalize directory permissions to Arch's standard 755. A build tree created
# under a group-writable umask (002) would otherwise bake 775 dirs into the
# package, which makes pacman warn "directory permissions differ" on install.
find "$STAGE" -type d -exec chmod 755 {} +

# Verify the binary expects Arch's /usr/lib layout, not Debian multiarch.
if strings "$STAGE/usr/bin/hardinfo2" | grep -q 'lib/loongarch64-linux-gnu/hardinfo2'; then
  echo "error: binary was built with Debian multiarch LIBPREFIX; rebuild with -DCMAKE_INSTALL_LIBDIR=lib" >&2
  exit 1
fi

# Compute installed size (KiB) from file sizes.
SIZE_KIB="$(find "$STAGE" -type f -printf '%s\n' | awk '{s+=$1} END {printf "%d", s/1024}')"

# Arch package metadata. Dependencies mirror the project's runtime list,
# minus sysbench/fwupd which are unavailable on loong64.
cat > "$STAGE/.PKGINFO" <<EOF
# Generated by acdcGGE loong64 build script
pkgname = $PKGNAME
pkgbase = $PKGNAME
xdata = pkgtype=pkg
pkgver = $PKGVER
pkgdesc = System Information and Benchmark for Linux Systems
url = https://www.hardinfo2.org
builddate = $PKGREL_DATE
packager = $PACKAGER
size = $SIZE_KIB
arch = $ARCH
license = GPL-2.0-or-later AND LGPL-2.1-or-later
provides = hardinfo
conflict = hardinfo
depend = gtk3
depend = libsoup3
depend = json-glib
depend = glib2
depend = zlib
depend = gawk
depend = dmidecode
depend = iperf3
depend = lm_sensors
depend = mesa-utils
depend = udisks2
depend = vulkan-tools
depend = xdg-utils
depend = xorg-xrandr
depend = qt5-base
EOF

cat > "$STAGE/.BUILDINFO" <<EOF
format = 2
pkgname = $PKGNAME
pkgbase = $PKGNAME
pkgver = $PKGVER
pkgarch = $ARCH
packager = $PACKAGER
builddate = $PKGREL_DATE
builddir = /build
startdir = /startdir
EOF

OUT="${PKGREL_OUT:-$SRC_DIR/${PKGNAME}-${VERSION}-1-${ARCH}.pkg.tar.zst}"
log "creating $OUT"
( cd "$STAGE" && bsdtar --zstd -cf "$OUT" .PKGINFO .BUILDINFO usr )

log "done:"
ls -lh "$OUT"
